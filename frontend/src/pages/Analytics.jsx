import React, { useState, useEffect, useCallback } from 'react';
import {
  BarChart3,
  RefreshCw,
  Clock,
  ArrowLeft,
  AlertCircle,
  Lock,
  Layers,
  Activity,
  Info
} from 'lucide-react';
import { Link } from 'react-router-dom';
import { apiService } from '../services/api';

import UserExecutiveKPIs from '../components/analytics/UserExecutiveKPIs';
import MultilingualUsagePanel from '../components/analytics/MultilingualUsagePanel';
import LanguagePerformanceTable from '../components/analytics/LanguagePerformanceTable';
import LanguageSwitchingPanel from '../components/analytics/LanguageSwitchingPanel';
import CodeMixedAnalysisPanel from '../components/analytics/CodeMixedAnalysisPanel';
import DocumentUsagePanel from '../components/analytics/DocumentUsagePanel';
import UserActivityTrendsChart from '../components/analytics/UserActivityTrendsChart';

const DATASET_INFO = {
  live: {
    title: 'LIVE APPLICATION DATA',
    badgeClass: 'bg-emerald-500/10 border-emerald-500/30 text-emerald-400',
    description: 'Analytics derived exclusively from genuine user interactions through the running application.',
  },
  test: {
    title: 'TEST / BENCHMARK DATA',
    badgeClass: 'bg-sky-500/10 border-sky-500/30 text-sky-400',
    description: 'Telemetry generated by automated regression tests and multilingual benchmark evaluation suites.',
  },
  fixture: {
    title: 'FIXTURE / DEMO DATA',
    badgeClass: 'bg-amber-500/10 border-amber-500/30 text-amber-400',
    description: 'Simulated operational telemetry created by the fixture generator for analytics demonstration.',
  },
  all: {
    title: 'ALL DATA (COMBINED)',
    badgeClass: 'bg-purple-500/10 border-purple-500/30 text-purple-400',
    description: 'Combined live, test benchmark, and synthetic fixture telemetry.',
  },
};

export default function Analytics() {
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [lastRefreshed, setLastRefreshed] = useState(null);
  const [globalError, setGlobalError] = useState(null);

  // Dataset Selection State (LIVE by default)
  const [selectedDataset, setSelectedDataset] = useState('live');

  // Complete Analytics Data Store
  const [data, setData] = useState({
    summary: null,
    languages: null,
    timeseries: null,
    users: null,
    languagePerf: null,
    switching: null,
    codeMixed: null,
    documents: null,
  });

  const fetchAnalytics = useCallback(async (isManualRefresh = false, env = selectedDataset) => {
    if (isManualRefresh) {
      setRefreshing(true);
    } else {
      setLoading(true);
    }
    setGlobalError(null);

    try {
      const results = await Promise.allSettled([
        apiService.getAnalyticsSummary(env),
        apiService.getAnalyticsLanguages(env),
        apiService.getAnalyticsTimeseries(env),
        apiService.getAnalyticsUsers(env),
        apiService.getAnalyticsLanguagePerformance(env),
        apiService.getAnalyticsLanguageSwitching(env),
        apiService.getAnalyticsCodeMixed(env),
        apiService.getAnalyticsDocuments(env),
      ]);

      const [
        summaryRes,
        languagesRes,
        timeseriesRes,
        usersRes,
        langPerfRes,
        switchingRes,
        codeMixedRes,
        docsRes,
      ] = results;

      const newData = {
        summary: summaryRes.status === 'fulfilled' ? summaryRes.value : null,
        languages: languagesRes.status === 'fulfilled' ? languagesRes.value : null,
        timeseries: timeseriesRes.status === 'fulfilled' ? timeseriesRes.value : null,
        users: usersRes.status === 'fulfilled' ? usersRes.value : null,
        languagePerf: langPerfRes.status === 'fulfilled' ? langPerfRes.value : null,
        switching: switchingRes.status === 'fulfilled' ? switchingRes.value : null,
        codeMixed: codeMixedRes.status === 'fulfilled' ? codeMixedRes.value : null,
        documents: docsRes.status === 'fulfilled' ? docsRes.value : null,
      };

      setData(newData);
      setLastRefreshed(new Date());

      if (summaryRes.status === 'rejected' && langPerfRes.status === 'rejected') {
        setGlobalError('Failed to load primary analytics endpoints. Please ensure backend is running.');
      }
    } catch (err) {
      setGlobalError(err.message || 'An unexpected error occurred while fetching analytics.');
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  }, [selectedDataset]);

  useEffect(() => {
    fetchAnalytics(false, selectedDataset);
  }, [fetchAnalytics, selectedDataset]);

  const handleDatasetChange = (newEnv) => {
    setSelectedDataset(newEnv);
    fetchAnalytics(false, newEnv);
  };

  const activeDatasetInfo = DATASET_INFO[selectedDataset] || DATASET_INFO.live;
  const hasData = (data.summary?.total_queries ?? data.summary?.total_queries_analyzed ?? 0) > 0;

  return (
    <div className="min-h-screen bg-slate-950 text-slate-100 p-4 sm:p-6 lg:p-8 space-y-6 max-w-7xl mx-auto">
      {/* Top Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 pb-5 border-b border-slate-800">
        <div className="space-y-1">
          <div className="flex items-center gap-3">
            <Link
              to="/"
              className="p-2 rounded-xl bg-slate-900 border border-slate-800 text-slate-400 hover:text-slate-200 hover:bg-slate-850 transition-colors"
              title="Return to Assistant"
            >
              <ArrowLeft className="w-4 h-4" />
            </Link>
            <div className="flex items-center gap-2.5">
              <div className="p-2.5 rounded-xl bg-indigo-500/10 border border-indigo-500/20 text-indigo-400">
                <BarChart3 className="w-5 h-5" />
              </div>
              <div>
                <h1 className="text-xl sm:text-2xl font-black tracking-tight text-slate-100">
                  Analytics
                </h1>
                <p className="text-xs text-slate-400 font-medium">
                  Understand user activity, language usage, and multilingual AI performance.
                </p>
              </div>
            </div>
          </div>
        </div>

        {/* Action Controls */}
        <div className="flex items-center gap-2.5">
          {/* Manual Refresh Button */}
          <button
            onClick={() => fetchAnalytics(true, selectedDataset)}
            disabled={refreshing || loading}
            className="flex items-center gap-2 px-3.5 py-1.5 rounded-xl bg-slate-900 hover:bg-slate-800 border border-slate-800 text-slate-300 text-xs font-semibold transition-colors cursor-pointer"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${refreshing ? 'animate-spin' : ''}`} />
            <span>{refreshing ? 'Refreshing...' : 'Refresh'}</span>
          </button>
        </div>
      </div>

      {/* Global Error Banner */}
      {globalError && (
        <div className="p-4 rounded-xl bg-rose-950/40 border border-rose-800/60 text-rose-300 text-xs flex items-center gap-3">
          <AlertCircle className="w-5 h-5 flex-shrink-0 text-rose-400" />
          <span>{globalError}</span>
        </div>
      )}

      {/* DATASET SELECTOR CONTROL BAR */}
      <div className="bg-slate-900/70 border border-slate-800 rounded-2xl p-4 space-y-3">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
          <div className="flex items-center gap-2 text-xs font-bold text-slate-300">
            <Layers className="w-4 h-4 text-indigo-400" />
            <span>Dataset Environment:</span>
          </div>

          {lastRefreshed && (
            <div className="text-[11px] text-slate-400 flex items-center gap-1 self-start sm:self-auto">
              <Clock className="w-3 h-3" />
              <span>Updated: {lastRefreshed.toLocaleTimeString()}</span>
            </div>
          )}
        </div>

        <div className="flex flex-wrap gap-2">
          <button
            onClick={() => handleDatasetChange('live')}
            className={`flex items-center gap-2 px-3.5 py-1.5 rounded-xl text-xs font-bold border transition-all cursor-pointer ${
              selectedDataset === 'live'
                ? 'bg-emerald-500/20 border-emerald-500/50 text-emerald-300 shadow-sm'
                : 'bg-slate-950/60 border-slate-800 text-slate-400 hover:text-slate-200 hover:border-slate-700'
            }`}
          >
            <div className={`w-2 h-2 rounded-full ${selectedDataset === 'live' ? 'bg-emerald-400 animate-pulse' : 'bg-slate-600'}`} />
            <span>LIVE</span>
          </button>

          <button
            onClick={() => handleDatasetChange('test')}
            className={`flex items-center gap-2 px-3.5 py-1.5 rounded-xl text-xs font-bold border transition-all cursor-pointer ${
              selectedDataset === 'test'
                ? 'bg-sky-500/20 border-sky-500/50 text-sky-300 shadow-sm'
                : 'bg-slate-950/60 border-slate-800 text-slate-400 hover:text-slate-200 hover:border-slate-700'
            }`}
          >
            <div className={`w-2 h-2 rounded-full ${selectedDataset === 'test' ? 'bg-sky-400' : 'bg-slate-600'}`} />
            <span>TEST / BENCHMARK</span>
          </button>

          <button
            onClick={() => handleDatasetChange('fixture')}
            className={`flex items-center gap-2 px-3.5 py-1.5 rounded-xl text-xs font-bold border transition-all cursor-pointer ${
              selectedDataset === 'fixture'
                ? 'bg-amber-500/20 border-amber-500/50 text-amber-300 shadow-sm'
                : 'bg-slate-950/60 border-slate-800 text-slate-400 hover:text-slate-200 hover:border-slate-700'
            }`}
          >
            <div className={`w-2 h-2 rounded-full ${selectedDataset === 'fixture' ? 'bg-amber-400' : 'bg-slate-600'}`} />
            <span>FIXTURE / DEMO</span>
          </button>

          <button
            onClick={() => handleDatasetChange('all')}
            className={`flex items-center gap-2 px-3.5 py-1.5 rounded-xl text-xs font-bold border transition-all cursor-pointer ${
              selectedDataset === 'all'
                ? 'bg-purple-500/20 border-purple-500/50 text-purple-300 shadow-sm'
                : 'bg-slate-950/60 border-slate-800 text-slate-400 hover:text-slate-200 hover:border-slate-700'
            }`}
          >
            <div className={`w-2 h-2 rounded-full ${selectedDataset === 'all' ? 'bg-purple-400' : 'bg-slate-600'}`} />
            <span>ALL DATA</span>
          </button>
        </div>

        {/* Dataset Description Banner */}
        <div className={`p-2.5 rounded-xl border flex items-start gap-2.5 text-xs ${activeDatasetInfo.badgeClass}`}>
          <Info className="w-4 h-4 flex-shrink-0 mt-0.5" />
          <div className="space-y-0.5">
            <span className="font-bold">{activeDatasetInfo.title}</span>
            <p className="text-slate-300 text-[11px] leading-relaxed">{activeDatasetInfo.description}</p>
          </div>
        </div>
      </div>

      {/* No Live Data Empty State Warning */}
      {!hasData && !loading && (
        <div className="p-8 rounded-2xl bg-slate-900/40 border border-slate-800 text-center space-y-2">
          <div className="inline-flex p-3 rounded-2xl bg-indigo-500/10 border border-indigo-500/20 text-indigo-400">
            <Activity className="w-5 h-5" />
          </div>
          <h3 className="text-sm font-bold text-slate-200">
            No live analytics available yet.
          </h3>
          <p className="text-xs text-slate-400 max-w-md mx-auto">
            {selectedDataset === 'live'
              ? 'Ask questions in the Ask AI assistant to generate genuine user telemetry.'
              : 'Run the benchmark test suite or fixture generator to populate this view.'}
          </p>
        </div>
      )}

      {/* SECTION 1 — FOUR KEY KPI CARDS */}
      <section>
        <UserExecutiveKPIs
          summary={data.summary}
          users={data.users}
          languagePerf={data.languagePerf}
        />
      </section>

      {/* SECTION 2 — LANGUAGE USAGE */}
      <section>
        <MultilingualUsagePanel
          languages={data.languages}
          languagePerf={data.languagePerf}
        />
      </section>

      {/* SECTION 3 — LANGUAGE PERFORMANCE */}
      <section>
        <LanguagePerformanceTable languagePerf={data.languagePerf} />
      </section>

      {/* SECTION 4 — LANGUAGE SWITCHING & ROMANIZED/CODE-MIXED USAGE */}
      <section className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        <LanguageSwitchingPanel switching={data.switching} />
        <CodeMixedAnalysisPanel codeMixed={data.codeMixed} />
      </section>

      {/* SECTION 5 — DOCUMENT USAGE */}
      <section>
        <DocumentUsagePanel documents={data.documents} />
      </section>

      {/* SECTION 6 — QUERY ACTIVITY (CLEAN REAL SERIES ONLY) */}
      <section>
        <UserActivityTrendsChart timeseries={data.timeseries} />
      </section>

      {/* COMPACT PRIVACY FOOTER */}
      <footer className="pt-4 pb-2 border-t border-slate-850 text-center text-xs text-slate-500 flex items-center justify-center gap-2">
        <Lock className="w-3.5 h-3.5 text-emerald-500/70" />
        <span>Zero-PII Privacy Architecture: SHA-256 HMAC anonymization, zero raw queries or document content stored.</span>
      </footer>
    </div>
  );
}
